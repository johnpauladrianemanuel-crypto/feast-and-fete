INSERT INTO public.menu_item_ingredients (menu_item_id, inventory_item_id)
SELECT menu.id, inventory.id
FROM ingredient_menu_links AS links
CROSS JOIN LATERAL unnest(string_to_array(links.menu_ids, ',')) AS linked_menu(menu_item_id)
JOIN public.menu_items AS menu ON menu.id = linked_menu.menu_item_id
JOIN public.inventory_items AS inventory ON inventory.id = links.ingredient_id
ON CONFLICT (menu_item_id, inventory_item_id) DO NOTHING;
