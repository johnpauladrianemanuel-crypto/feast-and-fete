-- Seed the ingredient catalog used by the current menu and connect each
-- ingredient to the dishes that use it. Stock quantities must be counted by
-- the restaurant before they are treated as accurate.

ALTER TABLE public.inventory_items
  ADD COLUMN IF NOT EXISTS is_counted BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.menu_item_ingredients (
  menu_item_id TEXT NOT NULL REFERENCES public.menu_items(id) ON DELETE CASCADE,
  inventory_item_id TEXT NOT NULL REFERENCES public.inventory_items(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (menu_item_id, inventory_item_id)
);

CREATE INDEX IF NOT EXISTS idx_menu_item_ingredients_inventory_item_id
  ON public.menu_item_ingredients(inventory_item_id);

ALTER TABLE public.menu_item_ingredients ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "admin_manage_menu_item_ingredients"
  ON public.menu_item_ingredients;
CREATE POLICY "admin_manage_menu_item_ingredients"
  ON public.menu_item_ingredients
  FOR ALL
  TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

